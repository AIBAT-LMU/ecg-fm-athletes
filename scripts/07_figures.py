def plot_roc_grid(inputs: Inputs, model: str, name: str, n_boot: int = N_BOOT_ROC) -> None:
    """Athlete-level ROC curve per label with a bootstrap confidence band.

    Uses the LMU label columns as recorded (without merging), so only labels with identical names
    in the label file and the model output are shown.
    """
    y_true_all = load_true_labels(inputs.labels_csv, merge_columns=False)
    segments = pd.read_csv(inputs.results[model].raw_segments, index_col="ecg_segment_id")
    segments["athlete_id"] = [athlete_id(idx) for idx in segments.index]
    y_score_all = segments.groupby("athlete_id").mean()

    athletes = sorted(list(set(y_true_all.index) & set(y_score_all.index)))
    labels = sorted(list(set(y_true_all.columns) & set(y_score_all.columns)))
    y_true, y_score = y_true_all.loc[athletes, labels], y_score_all.loc[athletes, labels]

    rng = np.random.RandomState(RNG_SEED)
    base_fpr = np.linspace(0, 1, 101)
    auroc: Dict[str, float] = {}
    bootstrap_tprs: Dict[str, np.ndarray] = {}
    for label in y_true.columns:
        truth, score = y_true[label], y_score[label]
        if len(truth.unique()) < 2:
            continue
        auroc[label] = roc_auc_score(truth, score)
        tprs = []
        for _ in range(n_boot):
            indices = resample(truth.index, random_state=rng)
            if len(truth.loc[indices].unique()) < 2:
                continue
            fpr_b, tpr_b, _ = roc_curve(truth.loc[indices], score.loc[indices])
            tpr_interp = np.interp(base_fpr, fpr_b, tpr_b)
            tpr_interp[0] = 0.0
            tprs.append(tpr_interp)
        bootstrap_tprs[label] = np.array(tprs)

    ranked = sorted(auroc, key=lambda k: auroc[k], reverse=True)
    n_cols = 4
    n_rows = math.ceil(len(ranked) / n_cols)
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(4.8, 3.6), sharex=True, sharey=True)
    axes_flat = axes.flatten()
    color = STYLE["secondary_lmu_color"]

    for ax, label in zip(axes_flat, ranked):
        fpr, tpr, _ = roc_curve(y_true[label], y_score[label])
        ax.plot(fpr, tpr, lw=0.9, color=color, zorder=2)
        lower = np.percentile(bootstrap_tprs[label], 2.5, axis=0)
        upper = np.percentile(bootstrap_tprs[label], 97.5, axis=0)
        ax.fill_between(base_fpr, lower, upper, color=color, alpha=0.3, zorder=1, linewidth=0)
        ax.plot([0, 1], [0, 1], color="black", lw=0.6, linestyle="--", zorder=3)
        ax.set_title(
            f"{label}\n(AUROC = {auroc[label]:.3f})", fontsize=5.5, fontweight="bold", pad=2
        )
        ax.grid(True, linestyle="--", alpha=0.6, linewidth=0.3)
        style_axes_spines(ax)
        ax.xaxis.set_major_formatter(FuncFormatter(zero_formatter))
        ax.yaxis.set_major_formatter(FuncFormatter(zero_formatter))
        ax.tick_params(
            axis="both",
            labelsize=5.0,
            direction="out",
            width=0.5,
            length=2.0,
            labelbottom=True,
            labelleft=True,
        )
    for ax in axes_flat[len(ranked) :]:
        ax.set_visible(False)

    fig.supxlabel("False Positive Rate (1 - Specificity)", fontsize=6.0, y=0.02, fontweight="bold")
    fig.supylabel("True Positive Rate (Sensitivity)", fontsize=6.0, x=0.02, fontweight="bold")
    plt.tight_layout(rect=[0.04, 0.04, 1, 0.96])
    save_figure(fig, inputs.figures_dir, name, svg=True)


