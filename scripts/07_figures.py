def zero_formatter(x: float, pos: int) -> str:
    return f"{x:.1f}" if x != 0 else "0"


def style_axes_spines(ax: plt.Axes) -> None:
    for spine in ax.spines.values():
        spine.set_visible(True)
        spine.set_edgecolor("#000000")
        spine.set_linewidth(STYLE["spine_linewidth"])


def save_figure(fig: plt.Figure, out_dir: Path, name: str, svg: bool = False) -> None:
    """Save a figure as PDF and PNG (optionally SVG) without an outer border and close it."""
    if svg:
        fig.savefig(out_dir / f"{name}.svg", format="svg", bbox_inches="tight")
    fig.patch.set_edgecolor("none")
    fig.patch.set_linewidth(0)
    fig.savefig(out_dir / f"{name}.pdf", format="pdf", bbox_inches="tight")
    fig.savefig(out_dir / f"{name}.png", format="png", dpi=600, bbox_inches="tight")
    plt.close(fig)
    logger.info("Saved %s", name)


