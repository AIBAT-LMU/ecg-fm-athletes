@dataclass(frozen=True)
class FigureData:
    """Evaluation results shared by the result figures."""

    true_labels: pd.DataFrame  # athlete x label, 0/1, merged to the model label set
    lmu_metrics: Dict[str, pd.DataFrame]  # per-label metrics on LMU, indexed by class
    physio_metrics: Dict[str, pd.DataFrame]  # per-label metrics on PhysioNet/CinC 2021
    athlete_probs: Dict[str, pd.DataFrame]  # athlete x label mean probabilities per model
    athletes: List[str]  # athletes with labels and predictions from every model
    common_labels: Dict[str, List[str]]  # labels present in both datasets, per model


@dataclass(frozen=True)
class Inputs:
    """Input locations given on the command line."""

    labels_csv: Path
    results: Dict[str, ResultPaths]
    processed_dir: Path
    figures_dir: Path

    def physionet_file(self, model: str, name: str) -> Path:
        return self.processed_dir / PHYSIONET_DIRS[model] / name


def load_figure_data(inputs: Inputs) -> FigureData:
    check_inputs(inputs.labels_csv, inputs.results)
    true_labels = load_true_labels(inputs.labels_csv)
    lmu_metrics = {m: load_per_label_report(inputs.results[m].agg_report) for m in MODELS}
    physio_metrics = {m: load_per_label_report(inputs.results[m].physionet_report) for m in MODELS}
    raw_segments = {m: pd.read_csv(inputs.results[m].raw_segments, index_col=0) for m in MODELS}

    labelled = set(true_labels.index)
    per_model = [labelled & set(athlete_id(s) for s in raw_segments[m].index) for m in MODELS]
    athletes = sorted(set.intersection(*per_model))

    common_labels = {
        m: sorted(
            list((set(physio_metrics[m]["Class"]) & set(lmu_metrics[m]["Class"])) - {"GLOBAL"})
        )
        for m in MODELS
    }
    athlete_probs = {m: aggregate_segments_to_athletes(raw_segments[m]) for m in MODELS}
    logger.info("Loaded results: %d LMU athletes", len(athletes))
    return FigureData(
        true_labels, lmu_metrics, physio_metrics, athlete_probs, athletes, common_labels
    )


def load_ages(inputs: Inputs) -> tuple:
    """Ages of the PhysioNet/CinC 2021 recordings (1-120 years) and of the LMU recordings."""
    physio_meta = pd.read_csv(
        inputs.physionet_file("ecgfm", "physionet2021_meta.csv"), low_memory=False
    )
    lmu_meta = pd.read_csv(inputs.processed_dir / LMU_META_FILE, low_memory=False)
    physio_age = pd.to_numeric(physio_meta["Age"], errors="coerce")
    physio_age = physio_age[(physio_age >= 1) & (physio_age <= 120)]
    lmu_age = pd.to_numeric(lmu_meta["age"], errors="coerce")
    return physio_age, lmu_age


