# Fig. 3, B4: domain shift per label
# --------------------------------------------------------------------------------------
def plot_domain_shift(
    data: FigureData,
    metrics: Sequence[str],
    height_ratio: float,
    out_dir: Path,
    name: str,
    main_text_layout: bool,
) -> None:
    """Per-label metric on PhysioNet/CinC 2021 and LMU, connected by a line (dot-to-dot plot).

    One row per metric, one column per model.

    Args:
        main_text_layout: layout of Fig. 3 (lettered panel titles, "Sensitivity" instead of
            "Recall"); otherwise the layout of Suppl. Fig. B4 (model names above the first row).
    """
    fig_w = TWO_COL_WIDTH
    fig, axes = plt.subplots(
        nrows=len(metrics), ncols=len(MODELS), figsize=(fig_w, fig_w * height_ratio)
    )
    legend_handles: List = []
    panel_idx = 0

    for row_idx, metric in enumerate(metrics):
        for col_idx, model in enumerate(MODELS):
            ax = axes[row_idx, col_idx]
            physio = data.physio_metrics[model].set_index("Class")
            lmu = data.lmu_metrics[model].set_index("Class")
            labels = data.common_labels[model]

            plot_data = (
                pd.DataFrame(
                    {
                        "Label": labels,
                        "PhysioNet": pd.to_numeric(physio.loc[labels, metric], errors="coerce"),
                        "LMU": pd.to_numeric(lmu.loc[labels, metric], errors="coerce"),
                    }
                )
                .dropna()
                .reset_index(drop=True)
            )
            if plot_data.empty:
                ax.axis("off")
                panel_idx += 1
                continue

            for j, row in plot_data.iterrows():
                ax.plot(
                    [row["PhysioNet"], row["LMU"]],
                    [j, j],
                    color="#000000",
                    linewidth=STYLE["bar_linewidth"],
                    zorder=1,
                )
            scatter_props = dict(s=20, edgecolor="#000000", linewidth=0.5, zorder=2)
            physio_points = ax.scatter(
                plot_data["PhysioNet"],
                plot_data.index,
                color=STYLE["primary_physionet_color"],
                label="PhysioNet/CinC 2021 Test",
                **scatter_props,
            )
            lmu_points = ax.scatter(
                plot_data["LMU"],
                plot_data.index,
                color=STYLE["primary_lmu_color"],
                label="LMU Athlete",
                **scatter_props,
            )

            ax.set_yticks(plot_data.index)
            if col_idx == 0:
                ax.set_yticklabels(
                    plot_data["Label"], fontsize=STYLE["tick_fontsize"], color="#000000"
                )
                ax.set_ylabel(
                    "Labels", fontsize=STYLE["label_fontsize"], fontweight="bold", color="#000000"
                )
            else:
                ax.set_yticklabels([])

            title_props = dict(fontsize=STYLE["title_fontsize"], fontweight="bold", pad=5)
            tick_props = dict(
                axis="both",
                which="major",
                labelsize=STYLE["tick_fontsize"],
                length=STYLE["tick_length"],
                width=STYLE["tick_width"],
            )
            if main_text_layout:
                x_label = metric.replace("Recall", "Sensitivity")
                ax.set_title(f"({chr(97 + panel_idx)}) {NAME_MAP[model]}", **title_props)
                ax.tick_params(colors="#000000", **tick_props)
            else:
                x_label = metric
                if row_idx == 0:
                    ax.set_title(NAME_MAP[model], color="#000000", **title_props)
                ax.tick_params(**tick_props)
            ax.set_xlabel(
                x_label, fontsize=STYLE["label_fontsize"], fontweight="bold", color="#000000"
            )

            ax.set_xlim(0, 1.05)
            ax.grid(
                axis="x",
                linestyle=STYLE["grid_linestyle"],
                alpha=STYLE["grid_alpha"],
                linewidth=STYLE["grid_linewidth"],
            )
            ax.xaxis.set_major_formatter(FuncFormatter(zero_formatter))
            style_axes_spines(ax)

            if not legend_handles:
                legend_handles = [physio_points, lmu_points]
            panel_idx += 1

    if legend_handles:
        fig.legend(
            handles=legend_handles,
            labels=["PhysioNet/CinC 2021 Test", "LMU Athlete"],
            loc="lower center",
            bbox_to_anchor=(0.5, 0.005),
            ncol=2,
            frameon=True,
            fontsize=STYLE["legend_fontsize"],
        )
    fig.tight_layout(rect=[0, 0.035 if main_text_layout else 0.03, 1, 0.98])
