def make_label_prevalence(inputs: Inputs, data: FigureData) -> None:
    """Prevalence of the 30 most frequent PhysioNet labels in both datasets, with counts."""
    meta = pd.read_csv(inputs.physionet_file("ecgfm", "physionet2021_meta.csv"), low_memory=False)
    label_cols = [col for col in meta.columns if col.startswith("label_")]
    physio_counts = meta[label_cols].sum()
    physio_counts.index = physio_counts.index.str.replace("label_", "")
    physio_prevalence = physio_counts / len(meta)

    lmu_counts = data.true_labels.loc[data.athletes].sum()
    lmu_prevalence = data.true_labels.loc[data.athletes].mean()

    all_labels = sorted(list(set(physio_prevalence.index) | set(lmu_prevalence.index)))
    table = pd.DataFrame({"Label": all_labels}).set_index("Label")
    table["LMU_Prevalence"] = lmu_prevalence.reindex(all_labels, fill_value=0) * 100
    table["PhysioNet_Prevalence"] = physio_prevalence.reindex(all_labels, fill_value=0) * 100
    table["LMU_Count"] = lmu_counts.reindex(all_labels, fill_value=0)
    table["PhysioNet_Count"] = physio_counts.reindex(all_labels, fill_value=0)
    table = table.sort_values(by="PhysioNet_Prevalence", ascending=False).reset_index().head(30)

    fig_w = TWO_COL_WIDTH
    fig, axes = plt.subplots(1, 2, figsize=(fig_w, fig_w * (8.0 / 16.0)), sharey=True)
    panels = [
        ("PhysioNet/CinC 2021", "PhysioNet", STYLE["primary_physionet_color"], "Label", False),
        ("LMU", "LMU", STYLE["primary_lmu_color"], "", True),
    ]
    for ax, (title, key, color, y_label, skip_zero_counts) in zip(axes, panels):
        sns.barplot(
            x=f"{key}_Prevalence",
            y="Label",
            data=table,
            ax=ax,
            orient="h",
            color=color,
            alpha=STYLE["fill_alpha"],
            edgecolor="#000000",
            linewidth=STYLE["bar_linewidth"],
        )
        ax.set_title(title, fontsize=STYLE["title_fontsize"], fontweight="bold")
        ax.set_xlabel("Prevalence (%)", fontsize=STYLE["label_fontsize"], fontweight="bold")
        if y_label:
            ax.set_ylabel(y_label, fontsize=STYLE["label_fontsize"], fontweight="bold")
        else:
            ax.set_ylabel("")
        for index, row in table.iterrows():
            count = row[f"{key}_Count"]
            if skip_zero_counts and not count > 0:
                continue
            ax.text(
                row[f"{key}_Prevalence"] + 1,
                index,
                f"{int(count):,}",
                color="black",
                ha="left",
                va="center",
                fontsize=STYLE["annot_fontsize"],
            )
    axes[1].tick_params(axis="y", length=0)

    for ax in axes:
        ax.set_xlim(0, 105)
        ax.xaxis.set_major_formatter(ticker.PercentFormatter(xmax=100))
        ax.grid(
            axis="x",
            linestyle=STYLE["grid_linestyle"],
            alpha=STYLE["grid_alpha"],
            linewidth=STYLE["grid_linewidth"],
        )
        ax.grid(axis="y", visible=False)
        style_axes_spines(ax)
        ax.tick_params(
            axis="both",
            which="major",
            labelsize=STYLE["tick_fontsize"],
            direction=STYLE["tick_direction"],
            width=STYLE["tick_width"],
            length=STYLE["tick_length"],
        )

    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    save_figure(fig, inputs.figures_dir, "figureA1_label_prevalence")


