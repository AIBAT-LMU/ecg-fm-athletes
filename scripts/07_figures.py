def plot_split_sources(inputs: Inputs) -> None:
    """Share of each source dataset within the train, validation and test split (Fig. A4)."""
    fig_w = TWO_COL_WIDTH
    fig, axes = plt.subplots(3, 1, figsize=(fig_w, fig_w * (11.0 / 14.0)))
    cmap = LinearSegmentedColormap.from_list(
        "custom_physionet", ["#FFFFFF", STYLE["primary_physionet_color"]], N=256
    )

    for ax, model in zip(axes, SPLIT_FIGURE_MODELS):
        splits_path = inputs.physionet_file(model, "splits.csv")
        if not splits_path.exists():
            ax.set_visible(False)
            continue
        splits = pd.read_csv(splits_path)
        # file names have the form physionet2021_<source dataset>_g<group>_...
        filenames = splits["save_path"].astype(str).str.split("/").str[-1]
        splits["sub_dataset"] = (
            filenames.str.replace("physionet2021_", "", regex=False).str.split("_g").str[0]
        )
        shares = pd.crosstab(splits["split"], splits["sub_dataset"], normalize="index") * 100
        shares = shares.loc[["train", "val", "test"]].fillna(0)

        sns.heatmap(
            shares,
            annot=True,
            fmt=".1f",
            cmap=cmap,
            linewidths=0.4,
            linecolor="#000000",
            ax=ax,
            annot_kws={"color": "black", "fontsize": STYLE["annot_fontsize"]},
            cbar=True,
            cbar_kws={"label": "Percentage (%)", "fraction": 0.02, "pad": 0.02},
        )
        cbar = ax.collections[0].colorbar
        cbar.ax.set_ylabel("Percentage (%)", fontsize=STYLE["label_fontsize"], fontweight="bold")
        cbar.ax.tick_params(
            labelsize=STYLE["tick_fontsize"],
            width=STYLE["tick_width"],
            length=STYLE["tick_length"],
        )
        cbar.outline.set_edgecolor("#000000")
        cbar.outline.set_linewidth(STYLE["spine_linewidth"])

        ax.set_ylabel(NAME_MAP[model], fontsize=STYLE["label_fontsize"], fontweight="bold")
        ax.set_xlabel("")
        ax.tick_params(axis="y", labelrotation=0, labelsize=STYLE["tick_fontsize"])
        ax.tick_params(axis="x", labelsize=STYLE["tick_fontsize"])
        style_axes_spines(ax)

    axes[-1].set_xlabel("Source Dataset", fontsize=STYLE["label_fontsize"], fontweight="bold")
    plt.tight_layout(h_pad=1.5)
    save_figure(fig, inputs.figures_dir, "figureA4_heatmap_splits")


def plot_split_labels(inputs: Inputs) -> None:
    """Share of the positive cases of each label in train, validation and test (Fig. A3)."""
    fig_w = TWO_COL_WIDTH
    fig, axes = plt.subplots(3, 1, figsize=(fig_w, fig_w * (12.0 / 14.0)), sharex=False)
    split_columns = {"Train": "Train (%)", "Val": "Validation (%)", "Test": "Test (%)"}

    for ax, model in zip(axes, SPLIT_FIGURE_MODELS):
        label_def_path = inputs.physionet_file(model, "label_def.csv")
        if not label_def_path.exists():
            ax.set_visible(False)
            continue
        label_def = pd.read_csv(label_def_path, index_col=0)
        label_def.index = label_def.index.str.replace("label_", "")
        counts = label_def[[col for col in label_def.columns if "pos_count" in col]].copy()
        counts.columns = [c.replace("pos_count_", "").capitalize() for c in counts.columns]
        total = counts.get("All", counts[list(split_columns)].sum(axis=1))
        shares = counts[list(split_columns)].div(total, axis=0) * 100
        shares = shares.rename(columns=split_columns).loc[total.sort_values(ascending=False).index]

        shares.plot(
            kind="bar",
            stacked=True,
            y=list(split_columns.values()),
            ax=ax,
            color=list(STYLE["split_palette"].values()),
            edgecolor="#000000",
            linewidth=0.5,
            legend=True,
        )
        legend = ax.get_legend()
        legend.set_title("Split", prop={"size": STYLE["legend_fontsize"]})
        for text in legend.get_texts():
            text.set_fontsize(STYLE["tick_fontsize"])
